func TestParseArgs(t *testing.T) {
	args := []string{"--source=MyMakefile", "--output=out.toml", "--force", "--dry-run", "--verbose"}
	opts := ParseArgs(args)

	if opts.SourcePath != "MyMakefile" {
		t.Errorf("SourcePath: got %q", opts.SourcePath)
	}
	if opts.OutputPath != "out.toml" {
		t.Errorf("OutputPath: got %q", opts.OutputPath)
	}
	if !opts.Force {
		t.Error("Force should be true")
	}
	if !opts.DryRun {
		t.Error("DryRun should be true")
	}
	if !opts.Verbose {
		t.Error("Verbose should be true")
	}
}

func TestSyncGeneratedRefreshesChangedMakefile(t *testing.T) {
	dir := t.TempDir()
	source := filepath.Join(dir, "Makefile")
	config := filepath.Join(dir, "lazy.toml")
	if err := os.WriteFile(source, []byte(".PHONY: all build\nall: build\nbuild:\n\tgo build\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := Run(MigrateOptions{SourcePath: source, OutputPath: config}); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(source, []byte(".PHONY: all build test\nall: build test\nbuild:\n\tgo build\ntest:\n\tgo test ./...\n"), 0644); err != nil {
		t.Fatal(err)
	}
	synced, err := SyncGenerated(config)
	if err != nil {
		t.Fatal(err)
	}
	if !synced {
		t.Fatal("expected generated config to be refreshed")
	}
	data, err := os.ReadFile(config)
	if err != nil {
		t.Fatal(err)
	}
	text := string(data)
	if !strings.Contains(text, "[commands.test]") || !strings.Contains(text, `dep = ["build", "test"]`) {
		t.Fatalf("updated targets were not synchronized:\n%s", text)
	}
	if synced, err = SyncGenerated(config); err != nil || synced {
		t.Fatalf("unchanged config should not be rewritten: synced=%v err=%v", synced, err)
	}
}

func TestSyncGeneratedLeavesHandWrittenConfigUntouched(t *testing.T) {
	dir := t.TempDir()
	config := filepath.Join(dir, "lazy.toml")
	original := []byte("[commands.hello]\nrun = [\"echo hi\"]\n")
	if err := os.WriteFile(config, original, 0644); err != nil {
		t.Fatal(err)
	}
	synced, err := SyncGenerated(config)
	if err != nil || synced {
		t.Fatalf("synced=%v err=%v", synced, err)
	}
	got, err := os.ReadFile(config)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != string(original) {
		t.Fatal("hand-written config changed")
	}
}

func TestSyncGeneratedPreservesManualCommandsWhenSourceUnchanged(t *testing.T) {
	dir := t.TempDir()
	source := filepath.Join(dir, "Makefile")
	config := filepath.Join(dir, "lazy.toml")
	if err := os.WriteFile(source, []byte("fmt:\n\tgo fmt ./...\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := Run(MigrateOptions{SourcePath: source, OutputPath: config}); err != nil {
		t.Fatal(err)
	}
	f, err := os.OpenFile(config, os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		t.Fatal(err)
	}
	if _, err = f.WriteString("\n[commands.fix]\nrun = [\"go fix ./...\"]\n"); err != nil {
		t.Fatal(err)
	}
	if err = f.Close(); err != nil {
		t.Fatal(err)
	}
	synced, err := SyncGenerated(config)
	if err != nil || synced {
		t.Fatalf("synced=%v err=%v", synced, err)
	}
	data, err := os.ReadFile(config)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), "[commands.fix]") {
		t.Fatal("manual command was erased")
	}
}

func TestSyncGeneratedUpgradesLegacyMarkerWithoutReplacingCommands(t *testing.T) {
	dir := t.TempDir()
	source := filepath.Join(dir, "Makefile")
	config := filepath.Join(dir, "lazy.toml")
	if err := os.WriteFile(source, []byte("fmt:\n\tgo fmt ./...\n"), 0644); err != nil {
		t.Fatal(err)
	}
	legacy := "# Generated by imlazy migrate from Makefile\n\n# imlazy-source: Makefile\n\n[commands.fix]\nrun = [\"go fix ./...\"]\n"
	if err := os.WriteFile(config, []byte(legacy), 0644); err != nil {
		t.Fatal(err)
	}
	synced, err := SyncGenerated(config)
	if err != nil || synced {
		t.Fatalf("synced=%v err=%v", synced, err)
	}
	data, err := os.ReadFile(config)
	if err != nil {
		t.Fatal(err)
	}
	text := string(data)
	if !strings.Contains(text, "[commands.fix]") || !strings.Contains(text, managedSourceHashPrefix) {
		t.Fatalf("legacy config was not safely upgraded:\n%s", text)
	}
}

