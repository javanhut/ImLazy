func TestRunDryRun(t *testing.T) {
	dir := t.TempDir()
	makefile := filepath.Join(dir, "Makefile")
	content := `.PHONY: build test

CC = gcc

# Build the project
build:
	$(CC) -o app main.c

# Run tests
test: build
	./run_tests.sh
`
	os.WriteFile(makefile, []byte(content), 0644)

	// Capture stdout
	oldStdout := os.Stdout
	r, w, _ := os.Pipe()
	os.Stdout = w

	err := Run(MigrateOptions{
		SourcePath: makefile,
		DryRun:     true,
	})

	w.Close()
	os.Stdout = oldStdout

	if err != nil {
		t.Fatal(err)
	}

	buf := make([]byte, 4096)
	n, _ := r.Read(buf)
	output := string(buf[:n])

	if !strings.Contains(output, "[commands.build]") {
		t.Error("dry run output should contain build command")
	}
	if !strings.Contains(output, "[commands.test]") {
		t.Error("dry run output should contain test command")
	}
}

