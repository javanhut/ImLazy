func TestConvertToTOMLBasic(t *testing.T) {
	ir := &MakefileIR{
		Variables: []MakeVar{
			{Name: "CC", Value: "gcc", Flavor: "="},
			{Name: "CFLAGS", Value: "-Wall -g", Flavor: ":="},
		},
		Targets: []MakeTarget{
			{
				Name:    "build",
				Comment: "Compile the project",
				Recipe:  []string{"$(CC) $(CFLAGS) -o app main.c"},
				IsPhony: true,
			},
		},
		DefaultGoal: "build",
	}

	toml := ConvertToTOML(ir)

	// Check header
	if !strings.Contains(toml, "# Generated by imlazy migrate from Makefile") {
		t.Error("missing header")
	}

	// Check settings
	if !strings.Contains(toml, `default = "build"`) {
		t.Error("missing default setting")
	}

	// Check variables
	if !strings.Contains(toml, `cc = "gcc"`) {
		t.Error("missing cc variable")
	}
	if !strings.Contains(toml, `cflags = "-Wall -g"`) {
		t.Error("missing cflags variable")
	}

	// Check command
	if !strings.Contains(toml, "[commands.build]") {
		t.Error("missing build command")
	}
	if !strings.Contains(toml, `desc = "Compile the project"`) {
		t.Error("missing description")
	}
	if !strings.Contains(toml, "{{cc}}") {
		t.Error("variable reference not converted")
	}
}

func TestConvertToTOMLWithEnv(t *testing.T) {
	ir := &MakefileIR{
		Variables: []MakeVar{
			{Name: "API_KEY", Value: "secret", Flavor: "=", Export: true},
			{Name: "CC", Value: "gcc", Flavor: "=", Export: false},
		},
		Targets: []MakeTarget{
			{Name: "build", Recipe: []string{"echo hi"}, IsPhony: true},
		},
		DefaultGoal: "build",
	}

	toml := ConvertToTOML(ir)

	if !strings.Contains(toml, "[env]") {
		t.Error("missing [env] section")
	}
	if !strings.Contains(toml, `API_KEY = "secret"`) {
		t.Error("missing exported variable in env section")
	}
	if !strings.Contains(toml, "[variables]") {
		t.Error("missing [variables] section")
	}
	if !strings.Contains(toml, `cc = "gcc"`) {
		t.Error("missing non-exported variable in variables section")
	}
}

func TestConvertToTOMLDepsFiltering(t *testing.T) {
	ir := &MakefileIR{
		Targets: []MakeTarget{
			{
				Name:          "all",
				Prerequisites: []string{"build", "test", "main.o"},
				IsPhony:       true,
			},
			{
				Name:    "build",
				Recipe:  []string{"go build"},
				IsPhony: true,
			},
			{
				Name:    "test",
				Recipe:  []string{"go test"},
				IsPhony: true,
			},
		},
		DefaultGoal: "all",
	}

	toml := ConvertToTOML(ir)

	// "all" should have dep = ["build", "test"] but NOT "main.o"
	if !strings.Contains(toml, `dep = ["build", "test"]`) {
		t.Errorf("dep list should only include actual targets, got:\n%s", toml)
	}
}

func TestConvertToTOMLTargetFiltering(t *testing.T) {
	ir := &MakefileIR{
		Targets: []MakeTarget{
			{Name: "build", Recipe: []string{"go build"}, IsPhony: true},
			{Name: "%.o", IsPattern: true, Recipe: []string{"gcc -c $<"}},
			{Name: ".SUFFIXES", IsDotTarget: true},
			{Name: "main.o", Recipe: []string{"gcc -c main.c"}},
		},
		DefaultGoal: "build",
	}

	toml := ConvertToTOML(ir)

	if !strings.Contains(toml, "[commands.build]") {
		t.Error("build should be included")
	}
	if strings.Contains(toml, "%.o") {
		t.Error("pattern rules should be filtered out")
	}
	if strings.Contains(toml, "SUFFIXES") {
		t.Error("dot targets should be filtered out")
	}
	if strings.Contains(toml, "main.o") {
		t.Error("file targets should be filtered out")
	}
}

func TestConvertToTOMLBuiltinRename(t *testing.T) {
	ir := &MakefileIR{
		Targets: []MakeTarget{
			{Name: "help", Recipe: []string{"echo help"}, IsPhony: true},
			{Name: "version", Recipe: []string{"echo v1"}, IsPhony: true},
		},
		DefaultGoal: "help",
	}

	toml := ConvertToTOML(ir)

	if !strings.Contains(toml, "[commands.make_help]") {
		t.Error("'help' should be renamed to 'make_help'")
	}
	if !strings.Contains(toml, "[commands.make_version]") {
		t.Error("'version' should be renamed to 'make_version'")
	}
	if !strings.Contains(toml, `default = "make_help"`) {
		t.Error("default goal should reference renamed target")
	}
}

