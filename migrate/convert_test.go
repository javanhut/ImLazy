func TestFilterVars(t *testing.T) {
	vars := []MakeVar{
		{Name: "CC", Export: false},
		{Name: "API_KEY", Export: true},
		{Name: "CFLAGS", Export: false},
	}

	nonExported := filterVars(vars, false)
	if len(nonExported) != 2 {
		t.Errorf("expected 2 non-exported, got %d", len(nonExported))
	}

	exported := filterVars(vars, true)
	if len(exported) != 1 {
		t.Errorf("expected 1 exported, got %d", len(exported))
	}
}

func TestFilterDeps(t *testing.T) {
	targetNames := map[string]bool{"build": true, "test": true}
	prereqs := []string{"build", "test", "main.o", "utils.o"}

	deps := filterDeps(prereqs, targetNames)
	if len(deps) != 2 {
		t.Fatalf("expected 2 deps, got %d", len(deps))
	}
	if deps[0] != "build" || deps[1] != "test" {
		t.Errorf("got %v", deps)
	}
}
